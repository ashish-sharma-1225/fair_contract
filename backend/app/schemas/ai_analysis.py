from typing import List, Optional, Literal
from pydantic import BaseModel, Field, ConfigDict


class ContractKeyTerm(BaseModel):
    """Specific commercial or operational clause extracted from the contract."""
    category: str = Field(..., description="e.g. payment, termination, renewal, liability, confidentiality")
    title: str = Field(..., description="Short descriptive title of the term")
    details: str = Field(..., description="Factual summary of what the contract specifies")
    source_quote: str = Field(..., description="Verbatim quote from the contract")
    page_number: int = Field(default=1, description="Page number where the term appears")

    model_config = ConfigDict(extra="ignore")


class ContractRiskItem(BaseModel):
    """Potentially risky, unbalanced, or ambiguous clause."""
    category: str = Field(default="other", description="payment, renewal, liability, jurisdiction, or other")
    title: str = Field(..., description="Concise risk title")
    severity: Literal["high", "medium", "low"] = Field(default="medium")
    reason: str = Field(..., description="Objective explanation of the risk or ambiguity")
    source_quote: str = Field(..., description="Exact excerpt from document")
    page_number: int = Field(default=1)
    remediation_advice: str = Field(..., description="Recommended contractual modification or safeguard")

    model_config = ConfigDict(extra="ignore")


class PolicyFindingItem(BaseModel):
    """Comparison of contract clauses against a specific organization policy."""
    policy_id: str
    policy_name: str
    status: Literal["violation", "compliant", "unverified", "not_applicable"] = Field(default="unverified")
    reason: str = Field(..., description="Analysis explaining why the clause violates, complies with, or lacks evidence for the policy")
    source_quote: str = Field(default="", description="Relevant contract excerpt or note if absent")
    page_number: int = Field(default=1)
    remediation_advice: str = Field(default="", description="Negotiation or drafting advice")

    model_config = ConfigDict(extra="ignore")


class StructuredAIAnalysisResult(BaseModel):
    """Comprehensive, validated structured AI analysis output generated by local Qwen model."""
    summary: str = Field(..., description="Factual executive summary of contract scope, duration, and core terms")
    parties: List[str] = Field(default_factory=list, description="Identified contracting parties and designated roles")
    key_terms: List[ContractKeyTerm] = Field(default_factory=list, description="Key commercial and operational clauses")
    risks: List[ContractRiskItem] = Field(default_factory=list, description="Identified contractual risks and ambiguous clauses")
    policy_findings: List[PolicyFindingItem] = Field(default_factory=list, description="Policy-by-policy compliance evaluations")
    missing_or_ambiguous_terms: List[str] = Field(default_factory=list, description="Important standard legal provisions that are missing or unclear")
    recommendations: List[str] = Field(default_factory=list, description="Prioritized recommendations for legal counsel")
    questions_for_human_review: List[str] = Field(default_factory=list, description="Specific questions the reviewer should verify with stakeholders")

    model_config = ConfigDict(extra="ignore")
